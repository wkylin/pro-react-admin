import { theme, type ThemeConfig } from 'antd'
import type { ThemeSettings } from './hooks'
import { getContrastingTextColor, mixThemeColors } from './contrast'
import { ADMIN_FONT_FAMILY, getThemeAccents, getThemePalette, type ThemeAppearance } from './palette'

export const createAdminTheme = (
  settings: Pick<ThemeSettings, 'colorPrimary' | 'compactAlgorithm'>,
  mode: ThemeAppearance
): ThemeConfig => {
  const palette = getThemePalette(mode)
  const dark = getThemePalette('dark')
  const accents = getThemeAccents(mode, settings.colorPrimary)
  const dangerAccents = getThemeAccents(mode, palette.danger)
  const switchAccents = getThemeAccents('light', settings.colorPrimary)
  const switchForeground = getContrastingTextColor(switchAccents.primary)
  const colorPrimary = accents.primary
  const selectedBg = mixThemeColors(palette.surface, colorPrimary, mode === 'dark' ? 0.12 : 0.06)
  const primaryTokens = {
    colorPrimary,
    colorPrimaryHover: accents.hover,
    colorPrimaryActive: accents.active,
    colorPrimaryText: colorPrimary,
    colorPrimaryTextHover: accents.hover,
    colorPrimaryTextActive: accents.active,
    colorLink: colorPrimary,
    colorLinkHover: accents.hover,
    colorLinkActive: accents.active,
  }
  const statusTokens = {
    colorInfo: palette.info,
    colorInfoText: palette.info,
    colorInfoBg: palette.infoBg,
    colorInfoBorder: mixThemeColors(palette.infoBg, palette.info, 0.2),
    colorSuccess: palette.success,
    colorSuccessText: palette.success,
    colorSuccessBg: palette.successBg,
    colorSuccessBorder: mixThemeColors(palette.successBg, palette.success, 0.2),
    colorWarning: palette.warning,
    colorWarningText: palette.warning,
    colorWarningBg: palette.warningBg,
    colorWarningBorder: mixThemeColors(palette.warningBg, palette.warning, 0.2),
    colorError: palette.danger,
    colorErrorHover: dangerAccents.hover,
    colorErrorActive: dangerAccents.active,
    colorErrorText: palette.danger,
    colorErrorTextHover: dangerAccents.hover,
    colorErrorTextActive: dangerAccents.active,
    colorErrorBg: palette.dangerBg,
    colorErrorBorder: mixThemeColors(palette.dangerBg, palette.danger, 0.2),
  }
  const baseAlgorithm = mode === 'dark' ? theme.darkAlgorithm : theme.defaultAlgorithm
  // Seed colors are derived again by AntD; pin the accessible roles in the map too.
  const accessibleAlgorithm: typeof theme.defaultAlgorithm = (...args) => ({
    ...baseAlgorithm(...args),
    ...primaryTokens,
    ...statusTokens,
  })
  const algorithms = [accessibleAlgorithm]
  if (settings.compactAlgorithm) algorithms.push(theme.compactAlgorithm)

  return {
    algorithm: algorithms,
    token: {
      ...primaryTokens,
      ...statusTokens,
      colorBgLayout: palette.canvas,
      colorBgContainer: palette.surface,
      colorBgElevated: palette.elevated,
      colorBgSpotlight: dark.elevated,
      colorBgMask: mode === 'dark' ? 'rgb(0 0 0 / 60%)' : 'rgb(24 24 24 / 36%)',
      colorText: palette.text,
      colorTextLightSolid: getContrastingTextColor(colorPrimary),
      colorTextSecondary: palette.secondary,
      colorTextTertiary: palette.muted,
      colorTextDescription: palette.muted,
      colorTextPlaceholder: palette.muted,
      colorBorder: palette.borderStrong,
      colorBorderSecondary: palette.border,
      colorFillTertiary: palette.hover,
      colorFillQuaternary: palette.canvas,
      colorBgTextHover: palette.hover,
      colorBgTextActive: palette.border,
      controlItemBgHover: palette.hover,
      controlItemBgActive: selectedBg,
      controlItemBgActiveHover: mixThemeColors(palette.hover, colorPrimary, 0.1),
      controlOutline: mixThemeColors(palette.surface, colorPrimary, 0.24),
      controlHeight: settings.compactAlgorithm ? 32 : 36,
      fontFamily: ADMIN_FONT_FAMILY,
      fontSize: 14,
      lineHeight: 20 / 14,
      fontSizeHeading1: 24,
      fontSizeHeading2: 20,
      fontSizeHeading3: 18,
      lineHeightHeading1: 32 / 24,
      lineHeightHeading2: 28 / 20,
      lineHeightHeading3: 28 / 18,
      fontWeightStrong: 600,
      borderRadius: 8,
      borderRadiusLG: 12,
      boxShadow: palette.shadow,
      boxShadowSecondary: palette.shadow,
      motionEaseInOut: 'cubic-bezier(0.22, 1, 0.36, 1)',
    },
    components: {
      Layout: {
        headerHeight: 56,
        headerBg: palette.surface,
        bodyBg: palette.canvas,
        footerBg: palette.canvas,
        siderBg: dark.canvas,
        lightSiderBg: palette.canvas,
        triggerBg: dark.surface,
        triggerColor: dark.text,
        lightTriggerBg: palette.surface,
        lightTriggerColor: palette.text,
      },
      Menu: {
        itemBg: palette.canvas,
        subMenuItemBg: palette.canvas,
        itemColor: palette.secondary,
        itemHoverColor: palette.text,
        itemSelectedColor: palette.text,
        subMenuItemSelectedColor: palette.text,
        itemHoverBg: palette.hover,
        itemSelectedBg: palette.hover,
        itemActiveBg: palette.hover,
        darkItemBg: dark.canvas,
        darkSubMenuItemBg: dark.canvas,
        darkPopupBg: dark.elevated,
        darkItemColor: dark.secondary,
        darkItemHoverColor: dark.text,
        darkItemSelectedColor: dark.text,
        darkItemHoverBg: dark.hover,
        darkItemSelectedBg: dark.hover,
        itemHeight: settings.compactAlgorithm ? 36 : 40,
        itemBorderRadius: 8,
        subMenuItemBorderRadius: 8,
        horizontalLineHeight: '56px',
        horizontalItemSelectedColor: colorPrimary,
        activeBarHeight: 0,
        activeBarBorderWidth: 0,
      },
      Button: {
        primaryColor: getContrastingTextColor(colorPrimary),
        dangerColor: getContrastingTextColor(palette.danger),
        fontWeight: 500,
        defaultShadow: 'none',
        primaryShadow: 'none',
        dangerShadow: 'none',
        defaultBg: palette.surface,
        defaultColor: palette.text,
        defaultBorderColor: palette.borderStrong,
        defaultHoverBg: palette.hover,
        defaultHoverColor: palette.text,
        defaultHoverBorderColor: palette.secondary,
        defaultActiveBg: palette.hover,
        defaultActiveColor: palette.text,
        defaultActiveBorderColor: palette.text,
      },
      Switch: {
        // One label/thumb color serves both states in AntD; give each track enough contrast.
        colorTextLightSolid: switchForeground,
        handleBg: switchForeground,
        colorTextQuaternary: dark.borderStrong,
        colorTextTertiary: mixThemeColors(dark.borderStrong, '#ffffff', 0.12),
        colorPrimary: switchAccents.primary,
        colorPrimaryHover: switchAccents.hover,
        colorPrimaryActive: switchAccents.active,
      },
      Input: {
        activeBg: palette.surface,
        hoverBg: palette.surface,
        activeBorderColor: colorPrimary,
        hoverBorderColor: palette.secondary,
        activeShadow: `0 0 0 2px ${mixThemeColors(palette.surface, colorPrimary, 0.2)}`,
      },
      Select: {
        selectorBg: palette.surface,
        optionActiveBg: palette.hover,
        optionSelectedBg: selectedBg,
        optionSelectedColor: palette.text,
        optionSelectedFontWeight: 500,
        multipleItemBg: palette.hover,
      },
      DatePicker: {
        cellHoverBg: palette.hover,
        cellActiveWithRangeBg: selectedBg,
        activeBorderColor: colorPrimary,
        hoverBorderColor: palette.secondary,
      },
      Table: {
        headerBg: mode === 'dark' ? palette.elevated : palette.canvas,
        headerColor: palette.secondary,
        headerSplitColor: palette.border,
        borderColor: palette.border,
        rowHoverBg: palette.hover,
        rowSelectedBg: selectedBg,
        rowSelectedHoverBg: mixThemeColors(palette.hover, colorPrimary, 0.1),
        footerBg: palette.surface,
        cellPaddingBlock: settings.compactAlgorithm ? 8 : 12,
        cellPaddingInline: 16,
      },
      Pagination: { itemBg: palette.surface, itemActiveBg: selectedBg },
      Card: { headerBg: 'transparent', bodyPadding: 24, headerFontSize: 16 },
      Modal: { contentBg: palette.elevated, headerBg: palette.elevated, footerBg: 'transparent', titleFontSize: 18 },
      Drawer: { colorBgElevated: palette.elevated },
      Dropdown: { colorBgElevated: palette.elevated, controlItemBgHover: palette.hover },
      Tooltip: { colorBgSpotlight: dark.elevated, colorTextLightSolid: dark.text },
      Tag: { defaultBg: palette.hover, defaultColor: palette.secondary, borderRadiusSM: 6 },
      Alert: { defaultPadding: '12px 16px', withDescriptionPadding: '16px' },
      Tabs: { itemSelectedColor: colorPrimary, itemHoverColor: accents.hover, cardBg: palette.canvas },
    },
  }
}
