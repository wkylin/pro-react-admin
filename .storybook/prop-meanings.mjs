function wordsFor(name) {
  const tokens = name
    .replace(/([a-z\d])([A-Z])/g, '$1 $2')
    .split(/\s+/)
    .map((token) => token.toLowerCase())
  const result = []
  for (let i = 0; i < tokens.length; i++) {
    const pair = `${tokens[i]}${tokens[i + 1]?.[0]?.toUpperCase() ?? ''}${tokens[i + 1]?.slice(1) ?? ''}`
    if (words[pair]) {
      result.push(words[pair])
      i++
    } else result.push(words[tokens[i]] ?? tokens[i])
  }
  return result.join('')
}

export function describeProp(component, prop) {
  const { name, type } = prop
  if (componentExact[component]?.[name]) return componentExact[component][name]
  if (exact[name]) return exact[name]
  const label = wordsFor(name)
  if (name.startsWith('on') && /^on[A-Z]/.test(name)) {
    const action = name.slice(2)
    return action.endsWith('Change')
      ? `${wordsFor(action.slice(0, -6))}变化时调用的回调；参数见类型列。`
      : `${wordsFor(action)}时调用的回调；参数见类型列。`
  }
  if (name.startsWith('render') && /^render[A-Z]/.test(name)) return `自定义${wordsFor(name.slice(6))}的渲染函数。`
  if (name.startsWith('get') && /^get[A-Z]/.test(name)) return `返回${wordsFor(name.slice(3))}的函数。`
  if (name.startsWith('show') && /^show[A-Z]/.test(name)) return `是否显示${wordsFor(name.slice(4))}。`
  if (name.startsWith('enable') && /^enable[A-Z]/.test(name)) return `是否启用${wordsFor(name.slice(6))}。`
  if (name.startsWith('default') && /^default[A-Z]/.test(name))
    return `非受控模式下${wordsFor(name.slice(7))}的初始值。`
  if (name.startsWith('initial') && /^initial[A-Z]/.test(name)) return `${wordsFor(name.slice(7))}的初始值。`
  if (name.endsWith('ClassName') || name.endsWith('Class'))
    return `${wordsFor(name.replace(/Class(Name)?$/, ''))}元素的 CSS 类名。`
  if (name.endsWith('Style') || name.endsWith('Styles'))
    return `${wordsFor(name.replace(/Styles?$/, ''))}区域的样式配置。`
  if (name.endsWith('Label')) return `${wordsFor(name.slice(0, -5))}控件显示的文案。`
  if (name.endsWith('Title')) return `${wordsFor(name.slice(0, -5))}显示的标题内容。`
  if (name.endsWith('Subtitle')) return `${wordsFor(name.slice(0, -8))}显示的副标题内容。`
  if (name.endsWith('Text')) return `${wordsFor(name.slice(0, -4))}显示的文字内容。`
  if (name.endsWith('Content')) return `${wordsFor(name.slice(0, -7))}显示的自定义内容。`
  if (name.endsWith('Image')) return `${wordsFor(name.slice(0, -5))}使用的图片地址。`
  if (name.endsWith('Author')) return `${wordsFor(name.slice(0, -6))}显示的作者内容。`
  if (name.endsWith('Publisher')) return `${wordsFor(name.slice(0, -9))}显示的出版方内容。`
  if (name.endsWith('Layout')) return `${wordsFor(name.slice(0, -6))}使用的版式。`
  if (name.endsWith('Position')) return `${wordsFor(name.slice(0, -8))}的位置配置。`
  if (name.endsWith('Color')) return `${wordsFor(name.slice(0, -5))}使用的颜色。`
  if (name.endsWith('Width')) return `${wordsFor(name.slice(0, -5))}的宽度。`
  if (name.endsWith('Height')) return `${wordsFor(name.slice(0, -6))}的高度。`
  if (name.endsWith('Count')) return `${wordsFor(name.slice(0, -5))}的数量。`
  if (name.endsWith('Size')) return `${wordsFor(name.slice(0, -4))}的尺寸。`
  if (name.endsWith('Delay')) return `${wordsFor(name.slice(0, -5))}前的等待时间。`
  if (name.endsWith('Duration')) return `${wordsFor(name.slice(0, -8))}持续的时间。`
  if (name.endsWith('Speed')) return `${wordsFor(name.slice(0, -5))}的速度。`
  if (name.endsWith('Url') || name.endsWith('URL')) return `${wordsFor(name.replace(/URL?$/, ''))}使用的资源地址。`
  if (name.endsWith('Ref')) return `指向${wordsFor(name.slice(0, -3))}元素或实例的 ref。`
  if (name.endsWith('Options')) return `${wordsFor(name.slice(0, -7))}的选项配置；字段见类型列。`
  if (name.endsWith('Props')) return `传给${wordsFor(name.slice(0, -5))}的属性配置。`
  if (type === 'boolean' || type === 'boolean | undefined') return `是否启用${label}。`
  if (/^\(.*\)\s*=>/.test(type)) return `用于计算${label}的函数；参数见类型列。`
  if (/\[\]|Array</.test(type)) return `用于${label}的条目列表；每项结构见类型列。`
  if (/ReactNode|React\.ReactNode/.test(type)) return `显示为${label}的 React 内容。`
  if (type === 'string') return `设置${label}文字或取值。`
  if (type === 'number') return `设置${label}数值。`
  return `设置${label}；可用类型见右侧。`
}
