import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('token', JSON.stringify({ token: 'admin@test.com' }))
    localStorage.setItem('user_role', 'super_admin')
    localStorage.setItem('i18nextLng', 'en')
  })
})

test('a customer conversation becomes an opportunity and a won customer in the same workspace', async ({ page }) => {
  await page.goto('/#/patterns/crm')
  await expect(page.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'New customer', exact: true }).click()
  const customerForm = page.getByRole('dialog', { name: 'New customer' })
  await customerForm.getByRole('textbox', { name: 'Company', exact: true }).fill('Harborline Demo Labs')
  await customerForm.getByRole('textbox', { name: 'Contact', exact: true }).fill('Maya Ellis')
  await customerForm.getByRole('textbox', { name: 'Email', exact: true }).fill('maya@harborline.example')
  await customerForm.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Harborline Demo Labs' })).toBeVisible()

  await page.getByRole('button', { name: 'Record follow-up', exact: true }).first().click()
  const followUp = page.getByRole('dialog', { name: 'Record follow-up' })
  await followUp
    .getByRole('textbox', { name: 'Conversation notes' })
    .fill('Reviewed the team rollout and agreed to prepare a proposal.')
  await followUp.getByLabel('Next follow-up', { exact: true }).fill('2027-02-12')
  await followUp.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(page.getByRole('region', { name: 'Follow-up history' })).toContainText('Reviewed the team rollout')

  await page.getByRole('button', { name: 'New opportunity', exact: true }).first().click()
  const opportunity = page.getByRole('dialog', { name: 'New opportunity' })
  await opportunity.getByRole('textbox', { name: 'Opportunity title' }).fill('Harborline team rollout')
  await opportunity.getByRole('spinbutton', { name: 'Amount (CNY)' }).fill('14235.75')
  await opportunity.getByLabel('Expected close date', { exact: true }).fill('2027-02-18')
  await opportunity.getByRole('button', { name: 'Save', exact: true }).click()
  const row = page.getByRole('row').filter({ hasText: 'Harborline team rollout' })
  await expect(row).toContainText('Discovery')
  await row.getByRole('button', { name: 'Prepare proposal', exact: true }).click()
  await expect(row).toContainText('Proposal')
  await row.getByRole('button', { name: 'Start negotiation', exact: true }).click()
  await row.getByRole('button', { name: 'Mark won', exact: true }).click()
  await page.getByRole('button', { name: 'Mark won', exact: true }).last().click()
  await expect(row).toContainText('Won')
  await expect(row).toContainText('Closed')
  await expect(row.getByRole('button', { name: 'Mark lost' })).toHaveCount(0)
  await expect(
    page.getByRole('region', { name: 'Customer profile' }).getByText('Customer', { exact: true })
  ).toBeVisible()
  await expect(page.getByLabel('Pipeline summary')).toContainText('14,235.75')

  await page.getByRole('button', { name: 'Back to customers', exact: true }).click()
  const customerRow = page.getByRole('row').filter({ hasText: 'Harborline Demo Labs' })
  await expect(customerRow).toContainText('Customer')
  await page
    .getByRole('navigation', { name: 'CRM workspace' })
    .getByRole('button', { name: 'Opportunities', exact: true })
    .click()
  await page.getByRole('textbox', { name: 'Search opportunity or company' }).fill('Harborline team rollout')
  await expect(page).toHaveURL(/search=Harborline/)
  await expect(page.getByRole('row').filter({ hasText: 'Harborline team rollout' })).toContainText('Won')
  await page.reload()
  await expect(page.getByText('No matching opportunities', { exact: true })).toBeVisible()
})

test('customer filters survive details and cancelling a draft preserves saved information', async ({ page }) => {
  await page.goto('/#/patterns/crm')
  const first = page.getByRole('region', { name: 'Customer records' }).getByRole('row').nth(1)
  const company = await first.getByRole('button').first().innerText()
  await page.getByRole('textbox', { name: 'Search company, contact, or email' }).fill(company)
  await expect(page).toHaveURL(/search=/)
  await expect(page.getByRole('region', { name: 'Customer records' }).getByRole('row')).toHaveCount(2)
  await page.getByRole('button', { name: company, exact: true }).click()
  await page.getByRole('button', { name: 'Edit customer', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Edit customer' })
  await editor.getByRole('textbox', { name: 'Company', exact: true }).fill('Unsaved customer change')
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click()
  await expect(editor.getByRole('textbox', { name: 'Company', exact: true })).toHaveValue('Unsaved customer change')
  await editor.getByRole('button', { name: 'Cancel', exact: true }).click()
  await page.getByRole('button', { name: 'Discard changes', exact: true }).click()
  await expect(page.getByRole('heading', { name: company, exact: true })).toBeVisible()
  await page
    .getByRole('navigation', { name: 'CRM workspace' })
    .getByRole('button', { name: 'Customers', exact: true })
    .click()
  await expect(page.getByRole('textbox', { name: 'Search company, contact, or email' })).toHaveValue(company)
  await page.getByRole('button', { name: company, exact: true }).click()
  await page.getByRole('button', { name: 'Back to customers', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Search company, contact, or email' })).toHaveValue(company)
  await page.getByRole('textbox', { name: 'Search company, contact, or email' }).fill('No company matches this query')
  await expect(page.getByText('No matching customers', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters', exact: true }).first().click()
  await expect(page.getByRole('button', { name: company, exact: true })).toBeVisible()
  await page.goto('/#/patterns/crm/customers/unknown-customer')
  await expect(page.getByText('Customer not found', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to customers', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible()
})

test('an opportunity can be closed as lost with a required reason', async ({ page }) => {
  await page.goto('/#/patterns/crm/opportunities')
  await expect(page.getByRole('heading', { name: 'Opportunities', exact: true })).toBeVisible()
  const row = page
    .getByRole('row')
    .filter({ has: page.getByRole('button', { name: 'Prepare proposal', exact: true }) })
    .first()
  const title = await row.getByRole('cell').first().locator('strong').innerText()
  await row.getByRole('button', { name: 'Mark lost', exact: true }).click()
  const editor = page.getByRole('dialog', { name: 'Mark lost' })
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(editor.getByText('Enter a loss reason with 4–500 characters.', { exact: true })).toBeVisible()
  await editor
    .getByRole('textbox', { name: 'Loss reason' })
    .fill('The customer postponed this project until the next planning cycle.')
  await editor.getByRole('button', { name: 'Save', exact: true }).click()
  const closed = page.getByRole('row').filter({ hasText: title })
  await expect(closed).toContainText('Lost')
  await expect(closed).toContainText('postponed this project')
  await expect(closed.getByRole('button', { name: 'Prepare proposal' })).toHaveCount(0)
})

test('mobile dark CRM keeps navigation and customer forms reachable', async ({ page }, testInfo) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/#/patterns/crm')
  await expect(page.getByRole('heading', { name: 'Customers', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Dark mode', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Light mode', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'New customer', exact: true })).toBeInViewport()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: testInfo.outputPath('crm-mobile-dark.png') })
  await page.getByRole('button', { name: 'New customer', exact: true }).click()
  await expect(
    page.getByRole('dialog', { name: 'New customer' }).getByRole('textbox', { name: 'Company', exact: true })
  ).toBeVisible()
})
