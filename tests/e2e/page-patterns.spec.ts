import { expect, test } from '@playwright/test'

test.beforeEach(async ({ page }) => {
  await page.addInitScript(() => {
    localStorage.setItem('token', JSON.stringify({ token: 'admin@test.com' }))
    localStorage.setItem('user_role', 'super_admin')
    localStorage.setItem('i18nextLng', 'en')
  })
})

test('basic form creates a request that can be found and progressed from the table', async ({ page }) => {
  await page.goto('/#/patterns/requests')
  await expect(page.getByRole('menuitem', { name: 'Page patterns' })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Search table', level: 1 })).toBeVisible()
  await expect(page.getByRole('row').filter({ hasText: 'Example request 01' })).toBeVisible()
  await page.getByRole('button', { name: 'New request' }).click()

  const form = page.getByRole('tabpanel', { name: 'Basic form' })
  await expect(form.getByRole('heading', { name: 'Basic form', level: 1 })).toBeVisible()
  await form.getByRole('textbox', { name: /Request title/ }).fill('Prepare a customer workspace')
  await form.getByRole('combobox', { name: /Category/ }).click()
  await page.getByText('Finance', { exact: true }).last().click()
  await form.getByRole('textbox', { name: /Owner/ }).fill('Morgan')
  await form.getByRole('button', { name: 'Submit request' }).click()

  await expect(page.getByRole('heading', { name: 'Submission result', level: 1 })).toBeVisible()
  await expect(page.getByText('Request created', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'View details' }).click()
  const detail = page.getByRole('tabpanel', { name: 'Request details' })
  await expect(detail.getByRole('heading', { name: 'Request details', level: 1 })).toBeVisible()
  await expect(detail.getByText('Prepare a customer workspace', { exact: true })).toBeVisible()
  await detail.getByRole('button', { name: 'Start work' }).click()
  await expect(detail.getByRole('button', { name: 'Mark complete' })).toBeVisible()
  await detail.getByRole('button', { name: 'Back to list' }).last().click()
  const list = page.getByRole('tabpanel', { name: 'Search table' })
  await list.getByRole('textbox', { name: 'Search requests' }).fill('Prepare a customer workspace')
  await list.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(list.getByRole('row').filter({ hasText: 'Prepare a customer workspace' })).toContainText('In progress')
})

test('step form preserves fields through review and creates a record in the same list', async ({ page }) => {
  await page.goto('/#/patterns/step-form')
  await expect(page.getByRole('heading', { name: 'Step form', level: 1 })).toBeVisible()
  await page.getByRole('textbox', { name: /Request title/ }).fill('Review a support workflow')
  await page.getByRole('button', { name: 'Next' }).click()
  await expect(page.getByRole('textbox', { name: /Owner/ })).toBeVisible()
  await page.getByRole('textbox', { name: /Owner/ }).fill('Taylor')
  await page.getByRole('button', { name: 'Next' }).click()
  await expect(page.getByRole('heading', { name: 'Review the request' })).toBeVisible()
  await expect(page.getByText('Review a support workflow', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Submit request' }).click()
  await expect(page.getByText('Request created', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Back to list' }).click()
  await page.getByRole('textbox', { name: 'Search requests' }).fill('Review a support workflow')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(page.getByRole('row').filter({ hasText: 'Review a support workflow' })).toBeVisible()
})

test('responsive request table exposes column settings and status filtering', async ({ page }) => {
  await page.goto('/#/patterns/requests')
  const list = page.getByRole('tabpanel', { name: 'Search table' })
  await expect(list.getByRole('columnheader', { name: 'No.' })).toBeVisible()
  await list.getByRole('button', { name: 'Column settings' }).click()
  await expect(page.getByRole('button', { name: 'All columns' })).toBeVisible()
  await list.getByRole('button', { name: 'Column settings' }).click()
  await list.getByRole('combobox', { name: 'Status' }).click()
  await page.getByText('In progress', { exact: true }).last().click()
  await list.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(list.getByRole('row').filter({ hasText: 'Example request 02' })).toBeVisible()
  await expect(list.getByRole('row').filter({ hasText: 'Example request 01' })).toHaveCount(0)
  await list.getByRole('button', { name: 'Reset' }).click()
  await expect(list.getByRole('row').filter({ hasText: 'Example request 01' })).toBeVisible()
})
